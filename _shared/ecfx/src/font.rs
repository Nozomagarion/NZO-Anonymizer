/// Width in pixels of `text` drawn at `size` pixels per font dot.
pub fn text_width(text: &str, size: usize) -> usize {
    let n = text.chars().count();
    if n == 0 { 0 } else { (n * 6 - 1) * size }
}

/// Draws `text` with its top-left corner at (x, y) in straight RGBA `color` blended over a
/// premultiplied image, `size` pixels per font dot.
pub fn draw_text(px: &mut [[f32; 4]], w: usize, h: usize, x: i32, y: i32, size: usize, text: &str, color: [f32; 4]) {
    let size = size.max(1) as i32;
    let mut cx = x;
    for ch in text.chars() {
        if let Some(rows) = glyph(ch) {
            for (ry, bits) in rows.iter().enumerate() {
                for rx in 0..5 {
                    if bits & (0x10 >> rx) != 0 {
                        fill_rect(px, w, h, cx + rx * size, y + ry as i32 * size, size, size, color);
                    }
                }
            }
        }
        cx += 6 * size;
    }
}

/// Blends a straight RGBA rectangle over a premultiplied image.
#[allow(clippy::too_many_arguments)]
pub fn fill_rect(px: &mut [[f32; 4]], w: usize, h: usize, x: i32, y: i32, rw: i32, rh: i32, color: [f32; 4]) {
    let x0 = x.max(0);
    let y0 = y.max(0);
    let x1 = (x + rw).min(w as i32);
    let y1 = (y + rh).min(h as i32);
    let a = color[3].clamp(0.0, 1.0);
    for yy in y0..y1 {
        for xx in x0..x1 {
            let p = &mut px[yy as usize * w + xx as usize];
            for k in 0..3 {
                p[k] = color[k] * a + p[k] * (1.0 - a);
            }
            p[3] = a + p[3] * (1.0 - a);
        }
    }
}
